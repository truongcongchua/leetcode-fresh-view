const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../content.js'), 'utf8');
const popup = fs.readFileSync(require('node:path').join(__dirname, '../popup.js'), 'utf8');
const wait = () => new Promise(r => setTimeout(r, 70));
(async () => {
  const dom = new JSDOM(`<body><main><section><header><div><a href="/problems/coin-change/">322. Coin Change</a></div><div id="solved"><span>Solved</span><svg></svg></div></header><div><div id="difficulty" class="text-difficulty-medium">Medium</div><button>Topics</button></div><article><p>Easy Medium Hard Solved</p></article></section></main></body>`, { url: 'https://leetcode.com/problems/coin-change/description/', runScripts: 'outside-only', pretendToBeVisual: true });
  let values = { enabled: true };
  let listener;
  dom.window.chrome = { storage: { local: { get: async () => values }, onChanged: { addListener: fn => listener = fn } }, runtime: { onMessage: { addListener() {} } } };
  dom.window.eval(source);
  await wait();
  const hidden = id => dom.window.document.getElementById(id).hasAttribute('data-lcfv-hidden');
  assert(hidden('solved')); assert(hidden('difficulty'));
  values = { hideSolved: false, hideDifficulty: true };
  listener({ hideSolved: {} }, 'local'); await wait();
  assert(!hidden('solved')); assert(hidden('difficulty'));
  values = { hideSolved: true, hideDifficulty: false };
  listener({ hideDifficulty: {} }, 'local'); await wait();
  assert(hidden('solved')); assert(!hidden('difficulty'));
  values = { hideSolved: false, hideDifficulty: false };
  listener({ hideSolved: {}, hideDifficulty: {} }, 'local'); await wait();
  assert(!hidden('solved')); assert(!hidden('difficulty'));
  assert(!dom.window.document.querySelector('article [data-lcfv-hidden]'));
  for (const level of ['Easy', 'Medium', 'Hard']) {
    values = { hideSolved: false, hideDifficulty: true };
    dom.window.document.body.innerHTML = `<main><section><div><div><div><div><div><div><h1>322. Coin Change</h1></div></div></div></div></div></div><div><div><span id="difficulty" class="text-olive">${level}</span></div><button>Topics</button><button>Companies</button></div><article><div id="prose">${level}</div></article></section><div class="monaco-editor"></div></main>`;
    listener({ hideDifficulty: {} }, 'local'); await wait();
    assert(hidden('difficulty'), `Class-independent ${level} with deeply nested title`);
    assert(!hidden('prose'), 'Do not hide exact difficulty words in article');
    values = { hideSolved: false, hideDifficulty: false };
    listener({ hideDifficulty: {} }, 'local'); await wait();
    assert(!hidden('difficulty'), `Restore ${level}`);
  }
  values = { hideSolved: true, hideDifficulty: true };
  dom.window.document.body.innerHTML = `<div class="flex w-full flex-1 flex-col gap-4 overflow-y-auto px-4 py-5"><div class="flex items-start justify-between gap-4"><div class="flex items-start gap-2"><div role="heading" aria-level="1" class="text-title-large" data-e2e-locator="question-title"><a href="/problems/coin-change/">322. Coin Change</a></div></div><div id="solved">Solved<svg></svg></div></div><div class="flex gap-1"><div id="difficulty" class="relative inline-flex rounded-full text-difficulty-easy dark:text-difficulty-easy">Easy</div><div><svg></svg>Topics</div><div><span>Companies</span></div></div><div data-track-load="description_content"><p>Easy</p></div><div contenteditable="true">Easy</div><textarea>Medium</textarea></div>`;
  listener({ hideDifficulty: {} }, 'local'); await wait();
  assert(hidden('difficulty'), 'Real LeetCode metadata panel with discussion editor must hide difficulty');
  assert(hidden('solved'));
  values = { hideSolved: true, hideDifficulty: false };
  listener({ hideDifficulty: {} }, 'local'); await wait();
  assert(!hidden('difficulty'));
  assert(hidden('solved'));
  dom.window.close();
  const ui = new JSDOM(fs.readFileSync(require('node:path').join(__dirname, '../popup.html'), 'utf8'), { runScripts: 'outside-only' });
  const writes = [];
  ui.window.chrome = { storage: { local: { get: async () => ({ enabled: true }), set: async v => writes.push(v) } }, tabs: { query: async () => [{ id: 1 }], sendMessage: async () => { throw Error('No receiver'); } } };
  ui.window.eval(popup); await wait();
  const toggle = ui.window.document.getElementById('hideSolved');
  assert(!toggle.disabled); toggle.checked = false;
  toggle.dispatchEvent(new ui.window.Event('change')); await wait();
  assert.deepEqual(writes.map(v => JSON.parse(JSON.stringify(v))), [{ hideSolved: false }]);
  assert(ui.window.document.getElementById('status').textContent.includes('refresh'));
  assert(!toggle.disabled);
  ui.window.close();
  console.log('PASS: four independent toggle combinations, legacy migration, surrounding content preserved, popup save and disconnected-tab feedback.');
})().catch(err => { console.error(err); process.exitCode = 1; });
